import { JSDOM } from 'jsdom';
import { Editor } from '@tiptap/core';
import StarterKit from '@tiptap/starter-kit';
import { Markdown } from '@tiptap/markdown';
import { richTextExtensions } from '../src/utils/richText.ts';
import { VideoEmbeds } from '../src/utils/videoEmbeds.ts';

let failures = 0;
function check(name, ok) { if (ok) console.log(`  ok   ${name}`); else { failures++; console.log(`  FAIL ${name}`); } }
console.log('\nrich text persistence');
const dom = new JSDOM('<!doctype html><html><body></body></html>', { pretendToBeVisual: true });
globalThis.window = dom.window;
globalThis.document = dom.window.document;
globalThis.Node = dom.window.Node;
globalThis.HTMLElement = dom.window.HTMLElement;
globalThis.MutationObserver = dom.window.MutationObserver;
globalThis.getComputedStyle = dom.window.getComputedStyle;
globalThis.requestAnimationFrame = dom.window.requestAnimationFrame.bind(dom.window);
globalThis.cancelAnimationFrame = dom.window.cancelAnimationFrame.bind(dom.window);
Object.defineProperty(globalThis, 'navigator', { value: dom.window.navigator, configurable: true });
const makeEditor = (value) => new Editor({ element: document.createElement('div'), extensions: [StarterKit, ...richTextExtensions, Markdown], content: value, contentType: 'markdown' });
const editor = makeEditor('Hello world');
editor.commands.setTextSelection({ from: 1, to: 6 });
editor.commands.setColor('#aabbcc');
editor.commands.setFontSize('24px');
const styledMarkdown = editor.getMarkdown();
const reopened = makeEditor(styledMarkdown);
check('saves styled text as inline HTML without losing content', styledMarkdown.includes('Hello') && styledMarkdown.includes('#aabbcc') && styledMarkdown.includes('24px'));
const styled = reopened.getJSON().content?.[0]?.content?.[0];
check('reopens font size and color from Markdown', styled?.marks?.some((mark) => mark.type === 'textStyle' && mark.attrs.color === '#aabbcc' && mark.attrs.fontSize === '24px'));
editor.commands.setTextSelection({ from: 7, to: 12 });
editor.commands.toggleHighlight();
const highlightedMarkdown = editor.getMarkdown();
const reopenedHighlight = makeEditor(highlightedMarkdown);
check('saves and reopens highlighted text', reopenedHighlight.getJSON().content?.[0]?.content?.some((node) => node.text === 'world' && node.marks?.some((mark) => mark.type === 'highlight')));
const combined = makeEditor('Bold color underline');
combined.commands.setTextSelection({ from: 1, to: 5 });
combined.commands.toggleBold(); combined.commands.toggleUnderline(); combined.commands.setColor('#123456'); combined.commands.setFontSize('32px');
const combinedMarkdown = combined.getMarkdown();
const reopenedCombined = makeEditor(combinedMarkdown);
const combinedMarks = reopenedCombined.getJSON().content?.[0]?.content?.find((node) => node.text?.includes('Bold'))?.marks ?? [];
check('round-trips combined bold, underline, color and size', combinedMarks.some((mark) => mark.type === 'bold') && combinedMarks.some((mark) => mark.type === 'underline') && combinedMarks.some((mark) => mark.type === 'textStyle' && mark.attrs.color === '#123456' && mark.attrs.fontSize === '32px'));
const special = makeEditor('');
special.commands.insertContent({ type: 'text', text: 'literal <b> & text' });
special.commands.selectAll(); special.commands.setColor('#445566'); special.commands.toggleHighlight();
const specialMarkdown = special.getMarkdown();
const reopenedSpecial = makeEditor(specialMarkdown);
check('preserves literal angle brackets and ampersands in styled text', reopenedSpecial.getText() === special.getText());
const linked = makeEditor('Watch this');
linked.commands.setTextSelection({ from: 1, to: 6 }); linked.commands.setLink({ href: 'https://example.com' }); linked.commands.setColor('#abcdef'); linked.commands.toggleHighlight();
const reopenedLink = makeEditor(linked.getMarkdown());
const linkMarks = reopenedLink.getJSON().content?.[0]?.content?.find((node) => node.text?.includes('Watch'))?.marks ?? [];
check('round-trips a link with highlight and color', linkMarks.some((mark) => mark.type === 'link' && mark.attrs.href === 'https://example.com') && linkMarks.some((mark) => mark.type === 'highlight') && linkMarks.some((mark) => mark.type === 'textStyle' && mark.attrs.color === '#abcdef'));
linked.commands.toggleUnderline();
const reopenedJustUnderline = makeEditor(linked.getMarkdown());
const justUnderlineMarks = reopenedJustUnderline.getJSON().content?.[0]?.content?.find((node) => node.text?.includes('Watch'))?.marks ?? [];
check('round-trips underline within a link without bold', justUnderlineMarks.some((mark) => mark.type === 'underline') && justUnderlineMarks.some((mark) => mark.type === 'link'));
linked.commands.toggleBold();
const reopenedLinkUnderline = makeEditor(linked.getMarkdown());
const linkUnderlineMarks = reopenedLinkUnderline.getJSON().content?.[0]?.content?.find((node) => node.text?.includes('Watch'))?.marks ?? [];
check('round-trips underline and bold within links', linkUnderlineMarks.some((mark) => mark.type === 'link') && linkUnderlineMarks.some((mark) => mark.type === 'bold') && linkUnderlineMarks.some((mark) => mark.type === 'underline'));
const videoEditor = new Editor({ element: document.createElement('div'), extensions: [StarterKit, VideoEmbeds, Markdown], content: '[A video](https://youtu.be/dQw4w9WgXcQ)\n\nAfter', contentType: 'markdown' });
const frame = videoEditor.view.dom.querySelector('.inline-video iframe');
check('renders validated video links inline without changing Markdown', frame?.getAttribute('src') === 'https://www.youtube-nocookie.com/embed/dQw4w9WgXcQ' && videoEditor.getMarkdown().includes('[A video](https://youtu.be/dQw4w9WgXcQ)') && !videoEditor.getMarkdown().includes('iframe'));
videoEditor.commands.insertContentAt(videoEditor.state.doc.content.size - 1, ' more');
check('retains the same iframe while unrelated text changes', videoEditor.view.dom.querySelector('.inline-video iframe') === frame);
videoEditor.destroy();
editor.destroy(); reopened.destroy(); reopenedHighlight.destroy(); combined.destroy(); reopenedCombined.destroy(); special.destroy(); reopenedSpecial.destroy(); linked.destroy(); reopenedLink.destroy(); reopenedJustUnderline.destroy(); reopenedLinkUnderline.destroy(); dom.window.close();

globalThis.__cometFailures = (globalThis.__cometFailures ?? 0) + failures;
